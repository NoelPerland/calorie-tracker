import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { mkdir } from 'node:fs/promises';
const base=process.env.TEST_URL||'http://localhost:3132/calorie-tracker/';
await mkdir('.qa',{recursive:true});
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const context=await browser.newContext({viewport:{width:1366,height:950}});
const page=await context.newPage();
const errors=[], external=[];
page.on('pageerror',error=>errors.push(error.message));
context.on('request',request=>{if(!request.url().startsWith(new URL(base).origin))external.push(request.url());});
try{
  await page.goto(base);
  await page.getByRole('button',{name:'Continue on this device'}).waitFor();
  await page.screenshot({path:'.qa/entry-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Continue on this device'}).click();
  await page.getByRole('button',{name:'Log food',exact:false}).click();
  await page.getByRole('button',{name:'Enter a meal'}).click();
  const dialog=page.getByRole('dialog',{name:'Log a meal'});
  await dialog.getByLabel('Food or meal name').fill('Oats and berries');
  await dialog.getByLabel('calories kcal').fill('420');
  await dialog.getByLabel('protein g').fill('18');
  await dialog.getByLabel('carbs g').fill('55');
  await dialog.getByLabel('fat g').fill('14');
  await dialog.getByLabel('Notes').fill('A relaxed breakfast.');
  await dialog.getByRole('button',{name:/Save (changes|meal)/}).click();
  await page.getByRole('heading',{name:'Oats and berries'}).waitFor();
  assert.equal(await page.locator('.calorie-number').innerText(),'420kcal');
  await page.reload();
  assert.equal(await page.getByRole('heading',{name:'Oats and berries'}).count(),0,'journal requires explicit resume');
  await page.getByRole('button',{name:'Continue on this device'}).click();
  await page.getByRole('button',{name:'Edit Oats and berries'}).click();
  await page.getByRole('dialog').getByLabel('calories kcal').fill('450');
  await page.getByRole('button',{name:/Save (changes|meal)/}).click();
  await page.waitForFunction(()=>document.querySelector('.calorie-number')?.textContent==='450kcal');
  await page.getByRole('button',{name:'History',exact:false}).click();
  await page.getByRole('button',{name:/Today.*1 entries/}).click();
  await page.getByRole('heading',{name:'Oats and berries'}).waitFor();
  await page.screenshot({path:'.qa/journal-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'.qa/journal-phone.png',fullPage:true});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  assert.equal(external.length,0,'manual guest entries make no remote requests');
  const isolated=await browser.newContext();
  const other=await isolated.newPage();
  await other.goto(base);
  await other.getByRole('button',{name:'Continue on this device'}).click();
  assert.equal(await other.getByRole('heading',{name:'Oats and berries'}).count(),0,'another browser has no guest entries');
  await isolated.close();
  await page.getByRole('button',{name:'Log food',exact:false}).click();
  assert.equal(await page.getByRole('button',{name:'Take a photo'}).count(),0);
  await page.getByRole('button',{name:'Scan a barcode'}).click();
  await context.route('https://world.openfoodfacts.org/**',route=>route.fulfill({json:{status:1,product:{product_name:'Barcode fixture',nutriments:{'energy-kcal_100g':100,proteins_100g:2,carbohydrates_100g:10,fat_100g:1}}}}));
  await page.getByLabel('Or enter the barcode').fill('7310865004703');
  await page.getByRole('button',{name:'Look up product'}).click();
  await page.getByRole('heading',{name:'Barcode fixture'}).waitFor();
  page.on('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'Delete Barcode fixture'}).click();
  await page.getByRole('heading',{name:'Barcode fixture'}).waitFor({state:'detached'});
  const second=await context.newPage();
  await second.goto(base);
  await second.getByRole('button',{name:'Continue on this device'}).click();
  await second.getByRole('heading',{name:'Oats and berries'}).waitFor();
  await page.getByRole('button',{name:'Erase journal',exact:true}).click();
  await page.getByRole('button',{name:'Continue on this device'}).waitFor();
  await second.getByRole('heading',{name:'Oats and berries'}).waitFor({state:'detached'});
  await page.getByRole('button',{name:'Continue on this device'}).click();
  assert.equal(await page.getByRole('heading',{name:'Oats and berries'}).count(),0);
  await page.getByRole('button',{name:'Leave device journal'}).click();
  await page.screenshot({path:'.qa/entry-phone.png',fullPage:true});
  await page.evaluate(()=>localStorage.setItem('calorie-tracker:guest:v1','broken'));
  await page.getByRole('button',{name:'Continue on this device'}).click();
  await page.getByText(/Cannot open device storage/).waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS guest create/edit/delete/history/reload; barcode fixture; explicit resume; browser isolation; cross-tab erase; corrupt storage; desktop/mobile. No cloud API calls from manual guest journal.');
} finally {await browser.close();}
